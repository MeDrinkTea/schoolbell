    private static void add(String label, String... aliases) {
        CANONICAL.put(normalize(label), label);
        for (String alias : aliases) CANONICAL.put(normalize(alias), label);
    }

    private static void localize(String russian, String ukrainian, String belarusian) {
        UKRAINIAN.put(russian, ukrainian);
        BELARUSIAN.put(russian, belarusian);
    }

    static String label(Context context, String raw) {
        String value = CANONICAL.get(normalize(raw));
        if (value == null) return raw;
        String language = context.getSharedPreferences("settings", Context.MODE_PRIVATE).getString("subjectLanguage", "app");
        if ("ru".equals(language)) return value;
        if ("uk".equals(language)) return UKRAINIAN.getOrDefault(value, value);
        if ("be".equals(language)) return BELARUSIAN.getOrDefault(value, value);
        if ("en".equals(language)) return AppStrings.tEnglish(value);
        if (AppStrings.ukrainian(context)) return UKRAINIAN.getOrDefault(value, value);
        if (AppStrings.belarusian(context)) return BELARUSIAN.getOrDefault(value, value);
        return AppStrings.t(context, value);
    }

    private static String normalize(String value) {
        return value == null ? "" : value.trim().toLowerCase(Locale.ROOT).replaceAll("\\s+", " ");
    }

